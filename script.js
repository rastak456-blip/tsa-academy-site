const originalTitle = document.title;
const translatableTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
  acceptNode(node) {
    const parent = node.parentElement;
    const text = node.nodeValue.trim();

    if (!text || !parent || parent.closest('script, style, noscript, .language-menu__list')) {
      return NodeFilter.FILTER_REJECT;
    }

    return NodeFilter.FILTER_ACCEPT;
  },
});

while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  translatableTextNodes.push({ node, source: node.nodeValue });
}

function translatedTitle(language) {
  if (language !== 'ko') return originalTitle;

  const parts = originalTitle.split(' · ');
  const translatedPage = koreanTranslations.get(parts[0]) || parts[0];
  return [translatedPage, ...parts.slice(1)].join(' · ');
}

function applyLanguage(language) {
  const nextLanguage = language === 'ko' ? 'ko' : 'en';
  const languageText = document.querySelector('.language-menu__text');

  document.documentElement.lang = nextLanguage;
  document.title = translatedTitle(nextLanguage);

  translatableTextNodes.forEach(({ node, source }) => {
    const trimmed = source.trim();
    const leading = source.match(/^\s*/)?.[0] || '';
    const trailing = source.match(/\s*$/)?.[0] || '';
    const translated = nextLanguage === 'ko' ? koreanTranslations.get(trimmed) : null;
    node.nodeValue = `${leading}${translated || trimmed}${trailing}`;
  });

  if (languageText) languageText.textContent = nextLanguage === 'ko' ? '한국어' : 'English';

  document.querySelectorAll('.language-menu__option').forEach((option) => {
    option.setAttribute('aria-pressed', String(option.dataset.language === nextLanguage));
  });
}

const menuToggle = document.querySelector('.site-header__toggle');
const mainMenu = document.querySelector('.main-menu');
const languageButton = document.querySelector('.language-menu__button');
const languageList = document.querySelector('.language-menu__list');
const languageOptions = document.querySelectorAll('.language-menu__option');
const mainMenuButtons = document.querySelectorAll('.main-menu__button');
const siteHeader = document.querySelector('.site-header');
const headerScrollToken = Number.parseFloat(
  getComputedStyle(document.documentElement).getPropertyValue('--scroll-header-threshold'),
);
const headerScrollThreshold = Number.isFinite(headerScrollToken)
  ? headerScrollToken
  : siteHeader?.offsetHeight || 0;
let headerScrollFrame = null;
let headerIsCompact = false;

function closeMainMenuGroups() {
  mainMenuButtons.forEach((button) => {
    button.setAttribute('aria-expanded', 'false');
    button.closest('.main-menu__group')?.classList.remove('main-menu__group--open');
  });
}

function updateHeaderState() {
  const nextCompactState = window.scrollY > headerScrollThreshold;

  if (nextCompactState !== headerIsCompact) {
    siteHeader?.classList.toggle('site-header--compact', nextCompactState);

    if (nextCompactState) closeMainMenuGroups();
    headerIsCompact = nextCompactState;
  }

  headerScrollFrame = null;
}

function requestHeaderUpdate() {
  if (headerScrollFrame !== null) return;
  headerScrollFrame = window.requestAnimationFrame(updateHeaderState);
}

function storedLanguage() {
  try {
    return window.localStorage.getItem('tsa-language') || 'en';
  } catch {
    return 'en';
  }
}

function storeLanguage(language) {
  try {
    window.localStorage.setItem('tsa-language', language);
  } catch {
    // Language switching still works for the current page when storage is unavailable.
  }
}

applyLanguage(storedLanguage());
updateHeaderState();

window.addEventListener('scroll', requestHeaderUpdate, { passive: true });
window.addEventListener('pageshow', requestHeaderUpdate);

menuToggle?.addEventListener('click', () => {
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';

  menuToggle.setAttribute('aria-expanded', String(!isOpen));
  mainMenu?.classList.toggle('main-menu--open', !isOpen);
});

const hoverPointer = window.matchMedia('(hover: hover) and (pointer: fine)');
const wideViewport = window.matchMedia('(min-width: 62.0625rem)');

mainMenuButtons.forEach((button) => {
  button.addEventListener('click', () => {
    // Hover and :focus-within already open the dropdown on a desktop pointer,
    // where a click would only pin it open until another group is clicked.
    if (hoverPointer.matches && wideViewport.matches) return;

    const group = button.closest('.main-menu__group');
    const isOpen = button.getAttribute('aria-expanded') === 'true';

    closeMainMenuGroups();

    button.setAttribute('aria-expanded', String(!isOpen));
    group?.classList.toggle('main-menu__group--open', !isOpen);
  });
});

languageButton?.addEventListener('click', () => {
  const isOpen = languageButton.getAttribute('aria-expanded') === 'true';

  languageButton.setAttribute('aria-expanded', String(!isOpen));
  languageList.hidden = isOpen;
});

languageOptions.forEach((option) => {
  option.addEventListener('click', () => {
    const selectedLanguage = option.dataset.language === 'ko' ? 'ko' : 'en';

    storeLanguage(selectedLanguage);
    applyLanguage(selectedLanguage);
    languageButton?.setAttribute('aria-expanded', 'false');
    languageList.hidden = true;
  });
});

document.addEventListener('click', (event) => {
  const languageMenu = document.querySelector('.language-menu');

  if (languageMenu && !languageMenu.contains(event.target)) {
    languageButton?.setAttribute('aria-expanded', 'false');
    languageList.hidden = true;
  }

  // A group opened by touch has no pointer to leave it, so close it from outside.
  if (mainMenu && !mainMenu.contains(event.target) && !menuToggle?.contains(event.target)) {
    closeMainMenuGroups();
  }
});

document.addEventListener('keydown', (event) => {
  if (event.key !== 'Escape') return;

  closeMainMenuGroups();
  languageButton?.setAttribute('aria-expanded', 'false');
  if (languageList) languageList.hidden = true;
});

const heroSlides = Array.from(document.querySelectorAll('.hero-slider__slide'));
const heroSlideTime = Number.parseFloat(
  getComputedStyle(document.documentElement).getPropertyValue('--time-hero-slide'),
);
const reduceHeroMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
let activeHeroSlide = 0;

function showNextHeroSlide() {
  activeHeroSlide = (activeHeroSlide + 1) % heroSlides.length;

  heroSlides.forEach((slide, index) => {
    slide.classList.toggle('hero-slider__slide--active', index === activeHeroSlide);
  });
}

if (heroSlides.length > 1 && Number.isFinite(heroSlideTime) && heroSlideTime > 0 && !reduceHeroMotion) {
  window.setInterval(showNextHeroSlide, heroSlideTime);
}

const courseTabLists = document.querySelectorAll('.course-tabs');

document.querySelectorAll('.esl-course-tabs').forEach((tabList) => {
  const tabs = Array.from(tabList.querySelectorAll('[role="tab"]'));
  const explorer = tabList.closest('.esl-course-explorer');
  const select = (selected) => {
    tabs.forEach((tab) => {
      const active = tab === selected;
      tab.setAttribute('aria-selected', String(active));
      tab.tabIndex = active ? 0 : -1;
      explorer.querySelector(`#${tab.getAttribute('aria-controls')}`).hidden = !active;
    });
  };
  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => select(tab));
    tab.addEventListener('keydown', (event) => {
      let next;
      if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
      else if (event.key === 'ArrowLeft') next = (index + tabs.length - 1) % tabs.length;
      else if (event.key === 'Home') next = 0;
      else if (event.key === 'End') next = tabs.length - 1;
      else return;
      event.preventDefault();
      select(tabs[next]);
      tabs[next].focus();
    });
  });
});

function selectCourseTab(tabList, selectedButton) {
  const scope = tabList.closest('.course-schedule') || document;

  tabList.querySelectorAll('.course-tabs__button').forEach((button) => {
    const isSelected = button === selectedButton;
    const panel = scope.querySelector(`#${button.getAttribute('aria-controls')}`);

    button.setAttribute('aria-selected', String(isSelected));
    button.setAttribute('tabindex', isSelected ? '0' : '-1');

    if (panel) panel.hidden = !isSelected;
  });
}

courseTabLists.forEach((tabList) => {
  const buttons = Array.from(tabList.querySelectorAll('.course-tabs__button'));

  buttons.forEach((button) => {
    button.addEventListener('click', () => selectCourseTab(tabList, button));
    button.addEventListener('keydown', (event) => {
      if (event.key !== 'ArrowRight' && event.key !== 'ArrowLeft') return;

      const step = event.key === 'ArrowRight' ? 1 : -1;
      const nextButton = buttons[(buttons.indexOf(button) + step + buttons.length) % buttons.length];

      event.preventDefault();
      selectCourseTab(tabList, nextButton);
      nextButton.focus();
    });
  });
});
